        "방 안의 소리가 멈추면 소리 에너지는 측정할 수 있는 속도로 줄어들어요. 캐나다 국립연구원(NRC) 건축음향 입문 자료(CBD-236)는 <b>잔향시간</b>(RT, Reverberation Time)을 소리가 60dB 줄어드는 데 걸리는 시간으로 정의하고, 이를 ‘RT = 60 ÷ 감쇠 속도(dB/초)’로 적어요. 기호 RT60이나 T60의 ‘60’이 바로 이 60dB를 뜻해요.\n\n왜 하필 60dB일까요? 미국 조지아주립대 HyperPhysics는 이렇게 설명해요. 기준을 ‘처음 크기에서 60dB 아래’로 잡으면 시험에 쓴 소리가 처음에 얼마나 컸는지와 상관없이 값을 비교할 수 있어요. 또 가장 큰 오케스트라 크레셴도가 약 100dB, 음악실의 좋은 배경 소음이 약 40dB 정도라 그 차이인 약 60dB가 오케스트라 음량 범위와 맞아요.\n\n잔향시간은 주파수마다 달라요. 방 안 재료의 흡음 성질이 주파수에 따라 다르기 때문이에요. NRC의 흡음 설계 자료(Building Research Note 163)는 낮은 주파수의 잔향시간이 중간 주파수보다 두 배가량 긴 경우도 흔하다고 적고 있어요. 그래서 잔향시간 하나만 적혀 있으면 어느 주파수 대역의 값인지 확인하는 것이 좋아요."
